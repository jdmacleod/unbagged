"""Flag source files that have grown past the size limits in CODING_STANDARDS.md.

Code files should stay under 400 lines, draw a warning past 500 and fail past 800.
Test files get half as much room again: 600, 750 and 1,200. Files that were
already past the fail limit when the check arrived are listed with their line
counts in tools/size_baseline.json; they may shrink but never grow, and a file
that drops back under the limit leaves the baseline for good.

    python -m tools.check_size                 check every file in scope
    python -m tools.check_size --files a b     check only these (pre-commit)
    python -m tools.check_size --report        everything over the preferred size
    python -m tools.check_size --update        lower the baseline to today's counts

Stdlib only, so it runs in pre-commit and CI without the app's environment. Ported
from the same check in a sibling project; the limits are the same, the scope is
this repository's.

It walks named source directories only. `data/` holds real reports, is never in
scope, and is not walked: the scope is a list of directories to enter, not a list
of things to skip.
"""

from __future__ import annotations

import argparse
import json
import os
import sys
from dataclasses import dataclass
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
BASELINE_NAME = "tools/size_baseline.json"

SCOPE = ("src/unbagged", "tests", "tools", "frontend/src")
EXTENSIONS = (".py", ".ts", ".tsx")
SKIP_DIRS = frozenset(
    {
        "node_modules",
        "__pycache__",
        ".venv",
        "dist",
        "build",
        "static",
        # Generated by tools/make_fixtures.py and checked by `make fixtures-check`;
        # a generator's size is its catalogue, not its complexity.
        "fixtures",
    }
)


@dataclass(frozen=True)
class Limits:
    prefer: int
    warn: int
    fail: int


CODE = Limits(prefer=400, warn=500, fail=800)
TESTS = Limits(prefer=600, warn=750, fail=1200)


@dataclass(frozen=True)
class Result:
    failures: list[str]
    warnings: list[str]
    notes: list[str]


def in_scope(rel: str) -> bool:
    """True for a repo-relative POSIX path the size check covers."""
    if not rel.endswith(EXTENSIONS) or rel.endswith(".d.ts"):
        return False
    parts = rel.split("/")
    if SKIP_DIRS.intersection(parts[:-1]):
        return False
    return any(rel == root or rel.startswith(root + "/") for root in SCOPE)


def is_test(rel: str) -> bool:
    name = rel.rsplit("/", 1)[-1]
    return (
        rel.startswith("tests/")
        or (name.startswith("test_") and name.endswith(".py"))
        or name.endswith((".test.ts", ".test.tsx", ".spec.ts", ".spec.tsx"))
    )


def limits_for(rel: str) -> Limits:
    return TESTS if is_test(rel) else CODE


def count_lines(path: Path) -> int:
    return len(path.read_text(encoding="utf-8", errors="replace").splitlines())


def walk(root: Path) -> list[str]:
    """Every in-scope file under the scope directories, repo-relative."""
    found: list[str] = []
    for top in SCOPE:
        base = root / top
        if not base.is_dir():
            continue
        for dirpath, dirnames, filenames in os.walk(base):
            dirnames[:] = sorted(d for d in dirnames if d not in SKIP_DIRS)
            for filename in filenames:
                rel = (Path(dirpath) / filename).relative_to(root).as_posix()
                if in_scope(rel):
                    found.append(rel)
    return sorted(found)


def load_baseline(path: Path) -> dict[str, int]:
    if not path.is_file():
        return {}
    data = json.loads(path.read_text(encoding="utf-8"))
    return {str(k): int(v) for k, v in data.items()}


def save_baseline(path: Path, baseline: dict[str, int]) -> None:
    ordered = dict(sorted(baseline.items()))
    path.write_text(json.dumps(ordered, indent=2) + "\n", encoding="utf-8")


def check(root: Path, files: list[str], baseline: dict[str, int]) -> Result:
    failures: list[str] = []
    warnings: list[str] = []
    notes: list[str] = []
    for rel in files:
        path = root / rel
        if not in_scope(rel) or not path.is_file():
            continue
        lines = count_lines(path)
        limits = limits_for(rel)
        recorded = baseline.get(rel)
        if recorded is not None:
            if lines > recorded:
                failures.append(
                    f"{rel}: {lines} lines, up from {recorded} in the size "
                    "baseline. Baselined files may only shrink: split it."
                )
            elif lines < recorded:
                notes.append(
                    f"{rel}: {lines} lines, down from {recorded}. Run "
                    "`make size-update` to lower the baseline."
                )
        elif lines > limits.fail:
            failures.append(
                f"{rel}: {lines} lines, over the {limits.fail}-line limit. "
                "Split it by responsibility."
            )
        elif lines > limits.warn:
            warnings.append(
                f"{rel}: {lines} lines, over the {limits.warn}-line warning "
                f"(prefer {limits.prefer} or fewer). Consider splitting it."
            )
    return Result(failures, warnings, notes)


def report(root: Path, baseline: dict[str, int]) -> list[str]:
    rows: list[tuple[int, str]] = []
    for rel in walk(root):
        lines = count_lines(root / rel)
        limits = limits_for(rel)
        if lines <= limits.prefer:
            continue
        if rel in baseline:
            tag = "baselined"
        elif lines > limits.fail:
            tag = "fail"
        elif lines > limits.warn:
            tag = "warn"
        else:
            tag = "over preferred"
        rows.append((lines, f"{lines:>6}  {rel}  ({tag})"))
    rows.sort(key=lambda row: (-row[0], row[1]))
    return [text for _, text in rows]


def update(root: Path, baseline: dict[str, int]) -> tuple[dict[str, int], list[str]]:
    """Lower recorded counts; drop files that are gone or back under the limit."""
    updated: dict[str, int] = {}
    changes: list[str] = []
    for rel, recorded in sorted(baseline.items()):
        path = root / rel
        if not path.is_file():
            changes.append(f"{rel}: gone, dropped from the baseline")
            continue
        lines = count_lines(path)
        if lines <= limits_for(rel).fail:
            changes.append(f"{rel}: {lines} lines, under the limit, dropped")
        elif lines < recorded:
            updated[rel] = lines
            changes.append(f"{rel}: {recorded} -> {lines}")
        else:
            updated[rel] = recorded
    return updated, changes


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Check source file sizes.")
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--files", nargs="*", help="check only these paths")
    mode.add_argument("--report", action="store_true", help="list files over prefer")
    mode.add_argument("--update", action="store_true", help="lower the baseline")
    parser.add_argument("--root", type=Path, default=REPO_ROOT, help=argparse.SUPPRESS)
    args = parser.parse_args(argv)

    root: Path = args.root.resolve()
    baseline_path = root / BASELINE_NAME
    baseline = load_baseline(baseline_path)

    if args.report:
        for row in report(root, baseline):
            print(row)
        return 0

    if args.update:
        updated, changes = update(root, baseline)
        save_baseline(baseline_path, updated)
        for change in changes:
            print(change)
        print(f"size baseline: {len(updated)} files")
        return 0

    if args.files is not None:
        files = [Path(f).as_posix().removeprefix("./") for f in args.files]
    else:
        files = walk(root)
    result = check(root, files, baseline)
    for note in result.notes:
        print(f"note: {note}")
    for warning in result.warnings:
        print(f"warning: {warning}")
    for failure in result.failures:
        print(f"error: {failure}", file=sys.stderr)
    if args.files is None:
        print(
            f"size: {len(files)} files, {len(result.warnings)} warnings, "
            f"{len(result.failures)} failures, {len(baseline)} baselined"
        )
    return 1 if result.failures else 0


if __name__ == "__main__":
    sys.exit(main())
